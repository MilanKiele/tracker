import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

const folder = new URL("../supabase/", import.meta.url);
const load = (name) => readFile(new URL(`migrations/${name}`, folder), "utf8");
const initial = await load("202610270001_initial_schema.sql");
const seedStart = initial.indexOf(
  "create or replace function public.seed_new_user()",
);
assert.ok(
  seedStart > 0,
  "The original schema boundary changed. Review the setup generator.",
);
let base = initial.slice(0, seedStart);
// Unlike historical migration 003, the setup never deletes existing catalog rows.
// It also never installs the original template-generating signup trigger.
base = base.replace("create extension if not exists pgcrypto;", "");
base = base.replace(
  "    execute format('create policy %I on public.%I for all using (user_id = auth.uid()) with check (user_id = auth.uid())', t || '_owner', t);",
  `    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = t || '_owner') then
      execute format('create policy %I on public.%I for all using (user_id = auth.uid()) with check (user_id = auth.uid())', t || '_owner', t);
    end if;`,
);
assert.ok(base.includes("if not exists (select 1 from pg_policies"));
const notifications = await load(
  "202610270002_meal_review_and_notifications.sql",
);
const ai = await load("202610270004_ai_native.sql");
const conversations = await load("202610270005_ai_conversations.sql");
const ownedTables = [
  ...`${base}\n${notifications}\n${conversations}`.matchAll(
    /create table (?:if not exists )?public\.([a-z_]+)\s*\(/g,
  ),
].map((match) => match[1]);
assert.equal(ownedTables.length, 25);
function repeatable(sql) {
  return sql
    .replace(/^create table public\./gm, "create table if not exists public.")
    .replace(
      /^create (unique )?index (?!if not exists )/gm,
      (_, unique = "") => `create ${unique}index if not exists `,
    )
    .replace(
      /^create function public\./gm,
      "create or replace function public.",
    )
    .replace(
      /^create policy ([a-z_]+) on public\.([a-z_]+)\s+[\s\S]*?;/gm,
      (statement, name, table) => `do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = '${table}' and policyname = '${name}') then
    ${statement}
  end if;
end $$;`,
    );
}
const output = `-- Everwell: complete setup / recovery for the Supabase SQL Editor.
-- Generated by npm run db:setup. Do not edit this generated file manually.
-- Run the WHOLE file in the SAME project used by NEXT_PUBLIC_SUPABASE_URL.
-- Supports an empty app schema, partially applied repo migrations, and 001-005.
-- Existing records are preserved. Repeat runs are supported.
-- Unknown/incompatible custom table definitions abort the transaction safely.

begin;

do $$ begin
  if to_regclass('auth.users') is null then
    raise exception 'Run this file in your existing Supabase project SQL Editor.';
  end if;
end $$;

${repeatable(base)}
${repeatable(notifications)}

-- Disable the legacy automatic sample-data seeder, without deleting user data.
drop trigger if exists on_auth_user_created_seed on auth.users;

${repeatable(ai)}

-- Private, user-owned AI chat history (text only; uploaded photos are not saved).
${repeatable(conversations)}

-- Preserve existing profiles; recover the identity of already registered users.
insert into public.profiles(id,user_id,full_name)
select id,id,raw_user_meta_data->>'full_name' from auth.users
on conflict do nothing;

grant usage on schema public to authenticated;
grant select, insert, update, delete on table ${ownedTables.map((table) => `public.${table}`).join(", ")} to authenticated;

notify pgrst, 'reload schema';
commit;
`;
await writeFile(new URL("setup.sql", folder), output);
console.log(
  "Generated supabase/setup.sql (complete, repeatable setup; no data cleanup).",
);
